"""Compile parametric surface expressions to Numba kernels (no SymPy).

A :class:`~optics.primitive.surface.Surface`'s ``(x(u, v), y(u, v), z(u, v))``
expressions are validated by :mod:`optics.numerical.expression`, lowered to
scalar source, and emitted into a small module written to a shared temp
directory and imported by name. The module exposes:

``eval_local(u, v)``
    scalar surface point (``njit``).
``eval_grid(us, vs)``
    batched surface points for array evaluation (``njit``).
``derivatives_local(u, v)``
    tangents ``(r_u, r_v)`` from finite differences, mirroring
    :mod:`optics.numerical.differentiation` (``njit``).

The ``eval``/``deriv`` ``cfunc`` pair has one fixed C signature for every
surface, so the nopython solver kernels compile (and disk-cache) once in total.
Tangents are numerical, so no symbolic derivatives are ever generated. Because
the supported expression grammar always lowers to nopython code, a compiled
surface is guaranteed to build: anything outside the grammar is rejected at
parse time, and compilation failures are raised rather than degraded.
"""

import functools
import hashlib
import importlib.util
import os
import sys
import tempfile
from collections.abc import Sequence
from typing import Any, NamedTuple

import numba
import numpy as np

from .. import constants as _c
from . import expression
from .desc import probe_njit_pair
from .differentiation import fd_step

_CODEGEN_TAG = "4"
_CODEGEN_DIR = os.path.join(tempfile.gettempdir(), "optics_codegen")

_GENERATED_MODULE = '''"""Generated by optics surface expression codegen; do not edit."""
import math

import numpy as np
from numba import cfunc, carray, njit, types
from numba.extending import intrinsic

# The cfuncs take raw output addresses (uint64) so every caller in the solver
# kernels sees one stable C signature; the int-to-pointer cast is confined to
# these cfunc bodies (which cannot be disk-cached anyway), keeping the nopython
# solver chain free of dynamic globals.
_UINT64 = types.uint64


@intrinsic
def _int_to_f64ptr(typingctx, addr):
    ptr = types.CPointer(types.float64)
    sig = ptr(addr)

    def codegen(context, builder, signature, args):
        llt = context.get_value_type(signature.return_type)
        return builder.inttoptr(args[0], llt)

    return sig, codegen


_EVAL_SIG = types.void(types.float64, types.float64, _UINT64)
_DERIV_SIG = types.void(types.float64, types.float64, _UINT64, _UINT64)


@njit(cache=True)
def _sdiv(a, b):
    """Division with numpy scalar semantics (nan/inf instead of ZeroDivisionError)."""
    if b == 0.0:
        if a == 0.0:
            return math.nan
        return math.copysign(math.inf, a)
    return a / b


@njit(cache=True)
def _smod(a, b):
    """Modulo with numpy scalar semantics (nan instead of ZeroDivisionError)."""
    if b == 0.0:
        return math.nan
    return a % b


@njit(cache=True)
def eval_local(u, v):
    return np.array([{x}, {y}, {z}], dtype=np.float64)


@njit(cache=True)
def eval_grid(us, vs):
    n = us.shape[0]
    out = np.empty((n, 3), dtype=np.float64)
    for i in range(n):
        out[i] = eval_local(us[i], vs[i])
    return out


# Finite-difference step and parameter domain, baked per surface. The policy is
# the Python mirror in optics.numerical.differentiation.
_HU = {hu}
_HV = {hv}
_UMIN = {umin}
_UMAX = {umax}
_VMIN = {vmin}
_VMAX = {vmax}


@njit(cache=True)
def _is_finite3(a):
    return math.isfinite(a[0]) and math.isfinite(a[1]) and math.isfinite(a[2])


@njit(cache=True)
def _partial(u, v, h, lo, hi, along_u):
    if along_u:
        coord = u
        if lo <= u - h and u + h <= hi:
            f = eval_local(u + h, v)
            b = eval_local(u - h, v)
            if _is_finite3(f) and _is_finite3(b):
                return (f - b) / (2.0 * h)
    else:
        coord = v
        if lo <= v - h and v + h <= hi:
            f = eval_local(u, v + h)
            b = eval_local(u, v - h)
            if _is_finite3(f) and _is_finite3(b):
                return (f - b) / (2.0 * h)
    base = eval_local(u, v)
    if not _is_finite3(base):
        return np.full(3, math.nan)
    center = 0.5 * (lo + hi)
    inward = 1.0 if center >= coord else -1.0
    for s in range(2):
        sign = inward if s == 0 else -inward
        step = h
        for _ in range({shrink}):
            nxt = coord + sign * step
            if nxt < lo or nxt > hi:
                step *= 0.5
                continue
            if along_u:
                p = eval_local(nxt, v)
            else:
                p = eval_local(u, nxt)
            if _is_finite3(p):
                return (p - base) / (sign * step)
            step *= 0.5
    return np.full(3, math.nan)


@njit(cache=True)
def derivatives_local(u, v):
    ru = _partial(u, v, _HU, _UMIN, _UMAX, True)
    rv = _partial(u, v, _HV, _VMIN, _VMAX, False)
    return ru, rv


@cfunc(_EVAL_SIG)
def eval_cfn(u, v, addr):
    out = carray(_int_to_f64ptr(addr), 3)
    p = eval_local(u, v)
    out[0] = p[0]
    out[1] = p[1]
    out[2] = p[2]


@cfunc(_DERIV_SIG)
def deriv_cfn(u, v, ru_addr, rv_addr):
    ru_out = carray(_int_to_f64ptr(ru_addr), 3)
    rv_out = carray(_int_to_f64ptr(rv_addr), 3)
    ru, rv = derivatives_local(u, v)
    ru_out[0] = ru[0]
    ru_out[1] = ru[1]
    ru_out[2] = ru[2]
    rv_out[0] = rv[0]
    rv_out[1] = rv[1]
    rv_out[2] = rv[2]
'''


class SurfaceFunctions(NamedTuple):
    """Everything a compiled parametric surface needs, in named fields."""

    x_src: str
    y_src: str
    z_src: str
    eval_local: Any
    eval_grid: Any
    derivatives_local: Any
    eval_cfn: Any
    deriv_cfn: Any


def _codegen_module_name(key: str) -> str:
    return f"optics_codegen_{key}"


def _codegen_key(
    x_src: str,
    y_src: str,
    z_src: str,
    u_min: float,
    u_max: float,
    v_min: float,
    v_max: float,
) -> str:
    payload = (
        f"{_CODEGEN_TAG}|{numba.__version__}|{x_src}|{y_src}|{z_src}|"
        f"{u_min!r}|{u_max!r}|{v_min!r}|{v_max!r}"
    )
    return hashlib.sha1(payload.encode("utf-8")).hexdigest()[:16]


def _import_generated_module(key: str, source: str) -> Any:
    name = _codegen_module_name(key)
    module = sys.modules.get(name)
    if module is not None:
        return module
    os.makedirs(_CODEGEN_DIR, exist_ok=True)
    path = os.path.join(_CODEGEN_DIR, f"gen_{key}.py")
    if not os.path.exists(path):
        tmp = f"{path}.{os.getpid()}.tmp"
        with open(tmp, "w", encoding="utf-8") as fh:
            fh.write(source)
        os.replace(tmp, path)
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load generated surface module {path!r}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def _build_njit_functions(
    x_src: str,
    y_src: str,
    z_src: str,
    u_range: Sequence[float],
    v_range: Sequence[float],
) -> "tuple[Any, Any, Any, Any, Any]":
    """Compile scalar/batch ``eval`` and finite-difference ``derivatives`` kernels.

    Validates every expression first, so an unsupported expression raises
    :class:`~optics.numerical.expression.ExpressionError`. Compilation failures
    are raised too: the supported grammar always lowers to nopython code, so a
    failure is a real error, not a reason to fall back.
    """
    x = expression.scalar_source(x_src)
    y = expression.scalar_source(y_src)
    z = expression.scalar_source(z_src)
    u_min, u_max = float(u_range[0]), float(u_range[1])
    v_min, v_max = float(v_range[0]), float(v_range[1])
    source = _GENERATED_MODULE.format(
        x=x,
        y=y,
        z=z,
        hu=fd_step(u_min, u_max),
        hv=fd_step(v_min, v_max),
        umin=repr(u_min),
        umax=repr(u_max),
        vmin=repr(v_min),
        vmax=repr(v_max),
        shrink=_c.FD_STEP_SHRINKS,
    )
    key = _codegen_key(x_src, y_src, z_src, u_min, u_max, v_min, v_max)
    module = _import_generated_module(key, source)
    module.eval_local(0.7, 0.35)
    module.derivatives_local(0.7, 0.35)
    module.eval_grid(np.array([0.1, 0.2]), np.array([0.3, 0.4]))
    if not probe_njit_pair(module.eval_cfn, module.deriv_cfn):
        raise RuntimeError("Could not compile surface cfunc pair")
    return (
        module.eval_local,
        module.eval_grid,
        module.derivatives_local,
        module.eval_cfn,
        module.deriv_cfn,
    )


@functools.lru_cache(maxsize=1)
def null_surface_cfuncs() -> "tuple[Any, Any]":
    """``(eval_cfn, deriv_cfn)`` pair for a constant-zero surface.

    Gives inert padded element contexts (``tracing.context._null_element_context``)
    the same ``cfunc`` types as real surfaces so the padded stack tuple keeps
    one Numba signature. The pair is never executed; it only has to exist
    with the right C signature, exactly like every other surface's pair.
    """
    _, _, _, eval_cfn, deriv_cfn = _build_njit_functions(
        "u", "v", "0", (0.0, 1.0), (0.0, 1.0)
    )
    return eval_cfn, deriv_cfn


@functools.lru_cache(maxsize=64)
def compile_parametric_surface(
    x_src: str,
    y_src: str,
    z_src: str,
    u_range: Sequence[float],
    v_range: Sequence[float],
) -> SurfaceFunctions:
    """Validate and compile ``(x, y, z)`` into Numba kernels and a cfunc pair."""
    eval_local, eval_grid, derivatives_local, eval_cfn, deriv_cfn = (
        _build_njit_functions(x_src, y_src, z_src, u_range, v_range)
    )
    return SurfaceFunctions(
        x_src=x_src,
        y_src=y_src,
        z_src=z_src,
        eval_local=eval_local,
        eval_grid=eval_grid,
        derivatives_local=derivatives_local,
        eval_cfn=eval_cfn,
        deriv_cfn=deriv_cfn,
    )
