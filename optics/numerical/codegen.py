"""Compile parametric surface expressions to Numba kernels (no SymPy).

A :class:`~optics.primitive.surface.Surface`'s ``(x(u, v), y(u, v), z(u, v))``
expressions are validated by :mod:`optics.numerical.expression`, lowered to
scalar source, and emitted into a small module written to a shared temp
directory and imported by name. The module holds only the surface-specific
code:

``eval_local(u, v)``
    scalar surface point (``njit``).
``eval_grid(us, vs)``
    batched surface points for array evaluation (``njit``).
``eval_cfn`` / ``deriv_cfn``
    the fixed-signature C callback pair; ``deriv_cfn`` delegates to the
    shared finite-difference kernel, sampling the surface through
    ``eval_cfn``.

Everything surface-independent -- the safe div/mod helpers, the finite-
difference tangent policy, and the inert null-surface cfunc pair -- lives in
:mod:`optics.numerical._codegen_runtime`, is compiled once at program loading
(warmed on import below), and is reused by every surface.

The ``eval``/``deriv`` ``cfunc`` pair has one fixed C signature for every
surface, so the shared derivative kernel and the nopython solver kernels
compile (and disk-cache) once in total. Tangents are numerical, so no symbolic
derivatives are ever generated. Because the supported expression grammar
always lowers to nopython code, a compiled surface is guaranteed to build:
anything outside the grammar is rejected at parse time, and compilation
failures are raised rather than degraded.
"""

import functools
import hashlib
import importlib.util
import os
import sys
import tempfile
from collections.abc import Sequence
from typing import Any, NamedTuple

import numba
import numpy as np

from . import _codegen_runtime, expression
from .desc import probe_njit_pair
from .differentiation import fd_step

_CODEGEN_TAG = "5"
_CODEGEN_DIR = os.path.join(tempfile.gettempdir(), "optics_codegen")

_GENERATED_MODULE = '''"""Generated by optics surface expression codegen; do not edit."""
import math

import numpy as np
from numba import carray, cfunc, njit

from optics.numerical._codegen_runtime import (
    DERIV_SIG,
    EVAL_SIG,
    _int_to_f64ptr,
    _sdiv,
    _smod,
    derivatives_rt,
)


@njit(cache=True)
def eval_local(u, v):
    return np.array([{x}, {y}, {z}], dtype=np.float64)


@njit(cache=True)
def eval_grid(us, vs):
    n = us.shape[0]
    out = np.empty((n, 3), dtype=np.float64)
    for i in range(n):
        out[i] = eval_local(us[i], vs[i])
    return out


# Finite-difference step and parameter domain, baked per surface: the only
# surface-specific inputs to the shared derivative kernel. The finite-
# difference policy itself lives in optics.numerical._codegen_runtime, is
# compiled once and disk-cached, and samples the surface through ``eval_cfn``
# below. The Python mirror is optics.numerical.differentiation.
_HU = {hu}
_HV = {hv}
_UMIN = {umin}
_UMAX = {umax}
_VMIN = {vmin}
_VMAX = {vmax}


@cfunc(EVAL_SIG)
def eval_cfn(u, v, addr):
    out = carray(_int_to_f64ptr(addr), 3)
    p = eval_local(u, v)
    out[0] = p[0]
    out[1] = p[1]
    out[2] = p[2]


@cfunc(DERIV_SIG)
def deriv_cfn(u, v, ru_addr, rv_addr):
    ru_out = carray(_int_to_f64ptr(ru_addr), 3)
    rv_out = carray(_int_to_f64ptr(rv_addr), 3)
    ru, rv = derivatives_rt(eval_cfn, u, v, _HU, _HV, _UMIN, _UMAX, _VMIN, _VMAX)
    ru_out[0] = ru[0]
    ru_out[1] = ru[1]
    ru_out[2] = ru[2]
    rv_out[0] = rv[0]
    rv_out[1] = rv[1]
    rv_out[2] = rv[2]
'''


class SurfaceFunctions(NamedTuple):
    """Everything a compiled parametric surface needs, in named fields."""

    x_src: str
    y_src: str
    z_src: str
    eval_local: Any
    eval_grid: Any
    derivatives_local: Any
    eval_cfn: Any
    deriv_cfn: Any


def _codegen_module_name(key: str) -> str:
    return f"optics_codegen_{key}"


def _codegen_key(
    x_src: str,
    y_src: str,
    z_src: str,
    u_min: float,
    u_max: float,
    v_min: float,
    v_max: float,
) -> str:
    payload = (
        f"{_CODEGEN_TAG}|{numba.__version__}|{x_src}|{y_src}|{z_src}|"
        f"{u_min!r}|{u_max!r}|{v_min!r}|{v_max!r}"
    )
    return hashlib.sha1(payload.encode("utf-8")).hexdigest()[:16]


def _import_generated_module(key: str, source: str) -> Any:
    name = _codegen_module_name(key)
    module = sys.modules.get(name)
    if module is not None:
        return module
    os.makedirs(_CODEGEN_DIR, exist_ok=True)
    path = os.path.join(_CODEGEN_DIR, f"gen_{key}.py")
    if not os.path.exists(path):
        tmp = f"{path}.{os.getpid()}.tmp"
        with open(tmp, "w", encoding="utf-8") as fh:
            fh.write(source)
        os.replace(tmp, path)
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load generated surface module {path!r}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def _build_njit_functions(
    x_src: str,
    y_src: str,
    z_src: str,
    u_range: Sequence[float],
    v_range: Sequence[float],
) -> "tuple[Any, Any, Any, Any, Any]":
    """Compile the surface-specific ``eval`` kernels and the cfunc pair.

    Only expression-dependent code compiles here: the finite-difference
    tangent kernel and the safe div/mod helpers are shared per-process code
    from ``optics.numerical._codegen_runtime`` (warmed at import) and are
    reused through the surface's ``eval_cfn`` callback.

    Validates every expression first, so an unsupported expression raises
    :class:`~optics.numerical.expression.ExpressionError`. Compilation failures
    are raised too: the supported grammar always lowers to nopython code, so a
    failure is a real error, not a reason to fall back.
    """
    x = expression.scalar_source(x_src)
    y = expression.scalar_source(y_src)
    z = expression.scalar_source(z_src)
    u_min, u_max = float(u_range[0]), float(u_range[1])
    v_min, v_max = float(v_range[0]), float(v_range[1])
    hu = fd_step(u_min, u_max)
    hv = fd_step(v_min, v_max)
    source = _GENERATED_MODULE.format(
        x=x,
        y=y,
        z=z,
        hu=hu,
        hv=hv,
        umin=repr(u_min),
        umax=repr(u_max),
        vmin=repr(v_min),
        vmax=repr(v_max),
    )
    key = _codegen_key(x_src, y_src, z_src, u_min, u_max, v_min, v_max)
    module = _import_generated_module(key, source)
    module.eval_local(0.7, 0.35)
    module.eval_grid(np.array([0.1, 0.2]), np.array([0.3, 0.4]))
    if not probe_njit_pair(module.eval_cfn, module.deriv_cfn):
        raise RuntimeError("Could not compile surface cfunc pair")

    def derivatives_local(u: float, v: float) -> "tuple[np.ndarray, np.ndarray]":
        return _codegen_runtime.derivatives_rt(
            module.eval_cfn, u, v, hu, hv, u_min, u_max, v_min, v_max
        )

    return (
        module.eval_local,
        module.eval_grid,
        derivatives_local,
        module.eval_cfn,
        module.deriv_cfn,
    )


@functools.lru_cache(maxsize=1)
def null_surface_cfuncs() -> "tuple[Any, Any]":
    """``(eval_cfn, deriv_cfn)`` pair for a constant-zero surface.

    Gives inert padded element contexts (``tracing.context._null_element_context``)
    the same ``cfunc`` types as real surfaces so the padded stack tuple keeps
    one Numba signature. The pair is a static, never-executed part of
    :mod:`optics.numerical._codegen_runtime` (compiled once with the shared
    kernels); the accessor stays so call sites keep one shape.
    """
    return _codegen_runtime.null_eval_cfn, _codegen_runtime.null_deriv_cfn


@functools.lru_cache(maxsize=64)
def compile_parametric_surface(
    x_src: str,
    y_src: str,
    z_src: str,
    u_range: Sequence[float],
    v_range: Sequence[float],
) -> SurfaceFunctions:
    """Validate and compile ``(x, y, z)`` into Numba kernels and a cfunc pair."""
    eval_local, eval_grid, derivatives_local, eval_cfn, deriv_cfn = (
        _build_njit_functions(x_src, y_src, z_src, u_range, v_range)
    )
    return SurfaceFunctions(
        x_src=x_src,
        y_src=y_src,
        z_src=z_src,
        eval_local=eval_local,
        eval_grid=eval_grid,
        derivatives_local=derivatives_local,
        eval_cfn=eval_cfn,
        deriv_cfn=deriv_cfn,
    )


_codegen_runtime.warmup()
