"""SymPy -> NumPy/Numba compilation of parametric surface expressions.

Compiles the ``(x(u, v), y(u, v), z(u, v))`` expressions behind a
:class:`~optics.primitive.surface.Surface` into lambdified NumPy callables
(the vectorized fallback path) and, when possible, into scalar ``njit``
kernels plus a ``cfunc`` pair with fixed C signatures. The latter are
emitted as a small module written to a shared temp directory and imported
by name, so every surface shares one argument type and the nopython solver
kernels compile (and disk-cache) once in total. Surfaces whose expressions
cannot be turned into nopython code keep using the lambdified path.
"""

import ast
import functools
import hashlib
import importlib.util
import os
import sys
import tempfile
from typing import Any, NamedTuple

import numba
import sympy as sp

from .desc import probe_njit_pair

_CODEGEN_TAG = "3"
_CODEGEN_DIR = os.path.join(tempfile.gettempdir(), "optics_codegen")

_GENERATED_MODULE = '''"""Generated by optics.surface expression codegen; do not edit."""
import math

import numpy as np
from numba import cfunc, carray, njit, types
from numba.extending import intrinsic

# The cfuncs take raw output addresses (uint64) so every caller in the
# solver kernels sees one stable C signature; the int-to-pointer cast is
# confined to these cfunc bodies (which cannot be disk-cached anyway),
# keeping the nopython solver chain free of dynamic globals.
_UINT64 = types.uint64


@intrinsic
def _int_to_f64ptr(typingctx, addr):
    ptr = types.CPointer(types.float64)
    sig = ptr(addr)

    def codegen(context, builder, signature, args):
        llt = context.get_value_type(signature.return_type)
        return builder.inttoptr(args[0], llt)

    return sig, codegen


_EVAL_SIG = types.void(types.float64, types.float64, _UINT64)
_DERIV_SIG = types.void(types.float64, types.float64, _UINT64, _UINT64)


@njit(cache=True)
def _sdiv(a, b):
    """Division with numpy scalar semantics (nan/inf instead of ZeroDivisionError)."""
    if b == 0.0:
        if a == 0.0:
            return math.nan
        return math.copysign(math.inf, a)
    return a / b


@njit(cache=True)
def _smod(a, b):
    """Modulo with numpy scalar semantics (nan instead of ZeroDivisionError)."""
    if b == 0.0:
        return math.nan
    return a % b


@njit(cache=True)
def eval_local(u, v):
    return np.array([{x}, {y}, {z}], dtype=np.float64)


@njit(cache=True)
def derivatives_local(u, v):
    return (
        np.array([{xu}, {yu}, {zu}], dtype=np.float64),
        np.array([{xv}, {yv}, {zv}], dtype=np.float64),
    )


@cfunc(_EVAL_SIG)
def eval_cfn(u, v, addr):
    out = carray(_int_to_f64ptr(addr), 3)
    p = eval_local(u, v)
    out[0] = p[0]
    out[1] = p[1]
    out[2] = p[2]


@cfunc(_DERIV_SIG)
def deriv_cfn(u, v, ru_addr, rv_addr):
    ru_out = carray(_int_to_f64ptr(ru_addr), 3)
    rv_out = carray(_int_to_f64ptr(rv_addr), 3)
    ru, rv = derivatives_local(u, v)
    ru_out[0] = ru[0]
    ru_out[1] = ru[1]
    ru_out[2] = ru[2]
    rv_out[0] = rv[0]
    rv_out[1] = rv[1]
    rv_out[2] = rv[2]
'''


class SurfaceFunctions(NamedTuple):
    """Everything a compiled parametric surface needs, in named fields."""

    x_expr: Any
    y_expr: Any
    z_expr: Any
    eval_x: Any
    eval_y: Any
    eval_z: Any
    d_x_du: Any
    d_y_du: Any
    d_z_du: Any
    d_x_dv: Any
    d_y_dv: Any
    d_z_dv: Any
    eval_njit: Any
    deriv_njit: Any
    eval_cfn: Any
    deriv_cfn: Any


class _SafeDivRewriter(ast.NodeTransformer):
    """Rewrite ``a / b`` and ``a % b`` into helpers with numpy scalar semantics.

    Numba's nopython mode raises ``ZeroDivisionError`` where NumPy would
    return ``inf``/``nan``; the generated surface code must keep the NumPy
    behavior the lambdified fallback has always had.
    """

    def _wrap(self, node: ast.BinOp, name: str) -> ast.Call:
        return ast.Call(
            func=ast.Name(id=name, ctx=ast.Load()),
            args=[node.left, node.right],
            keywords=[],
        )

    def visit_BinOp(self, node: ast.BinOp) -> Any:
        self.generic_visit(node)
        if isinstance(node.op, ast.Div):
            return self._wrap(node, "_sdiv")
        if isinstance(node.op, ast.Mod):
            return self._wrap(node, "_smod")
        return node


def _scalar_code(expr: sp.Expr) -> str:
    """SymPy expression -> numba-compatible scalar Python source."""
    code = sp.printing.pycode(expr)
    tree = ast.parse(code, mode="eval")
    tree = _SafeDivRewriter().visit(tree)
    ast.fix_missing_locations(tree)
    return ast.unparse(tree)


def _codegen_module_name(key: str) -> str:
    return f"optics_codegen_{key}"


def _codegen_key(x_src: str, y_src: str, z_src: str) -> str:
    payload = f"{_CODEGEN_TAG}|{numba.__version__}|{x_src}|{y_src}|{z_src}"
    return hashlib.sha1(payload.encode("utf-8")).hexdigest()[:16]


def _import_generated_module(key: str, source: str) -> Any:
    name = _codegen_module_name(key)
    module = sys.modules.get(name)
    if module is not None:
        return module
    os.makedirs(_CODEGEN_DIR, exist_ok=True)
    path = os.path.join(_CODEGEN_DIR, f"gen_{key}.py")
    if not os.path.exists(path):
        tmp = f"{path}.{os.getpid()}.tmp"
        with open(tmp, "w", encoding="utf-8") as fh:
            fh.write(source)
        os.replace(tmp, path)
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load generated surface module {path!r}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def _build_njit_functions(
    x_expr: sp.Expr,
    y_expr: sp.Expr,
    z_expr: sp.Expr,
    x_src: str,
    y_src: str,
    z_src: str,
) -> "tuple[Any, Any, Any, Any]":
    """Compile scalar ``eval_local``/``derivatives_local`` njit kernels.

    Returns ``(None, None, None, None)`` when the expressions cannot be
    turned into nopython code; callers then keep using the lambdified NumPy
    path. The ``cfunc`` pair exposes the same math through a C function
    pointer type, which is identical for every surface, so the solver
    kernels compile (and disk-cache) once instead of once per surface.
    """
    u = sp.symbols("u")
    v = sp.symbols("v")
    try:
        source = _GENERATED_MODULE.format(
            x=_scalar_code(x_expr),
            y=_scalar_code(y_expr),
            z=_scalar_code(z_expr),
            xu=_scalar_code(sp.diff(x_expr, u)),
            yu=_scalar_code(sp.diff(y_expr, u)),
            zu=_scalar_code(sp.diff(z_expr, u)),
            xv=_scalar_code(sp.diff(x_expr, v)),
            yv=_scalar_code(sp.diff(y_expr, v)),
            zv=_scalar_code(sp.diff(z_expr, v)),
        )
        key = _codegen_key(x_src, y_src, z_src)
        module = _import_generated_module(key, source)
        eval_fn = module.eval_local
        deriv_fn = module.derivatives_local
        eval_fn(0.7, 0.35)
        deriv_fn(0.7, 0.35)
        if not probe_njit_pair(module.eval_cfn, module.deriv_cfn):
            return None, None, None, None
        return eval_fn, deriv_fn, module.eval_cfn, module.deriv_cfn
    except Exception:
        return None, None, None, None


@functools.lru_cache(maxsize=1)
def null_surface_cfuncs() -> "tuple[Any, Any]":
    """``(eval_cfn, deriv_cfn)`` pair for a constant-zero surface.

    Gives inert padded element contexts (``refraction._null_element_context``)
    the same ``cfunc`` types as real surfaces so the padded stack tuple keeps
    one Numba signature. The pair is never executed; it only has to exist
    with the right C signature, exactly like every other surface's pair.
    """
    x_expr = sp.parse_expr("u")
    y_expr = sp.parse_expr("v")
    z_expr = sp.parse_expr("0.0")
    _, _, eval_cfn, deriv_cfn = _build_njit_functions(
        x_expr, y_expr, z_expr, "u", "v", "0.0"
    )
    if eval_cfn is None or deriv_cfn is None:
        raise RuntimeError("Could not compile inert surface cfuncs")
    return eval_cfn, deriv_cfn


@functools.lru_cache(maxsize=64)
def compile_parametric_surface(
    x_src: str, y_src: str, z_src: str
) -> SurfaceFunctions:
    u = sp.symbols("u")
    v = sp.symbols("v")
    x_expr = sp.parse_expr(x_src)
    y_expr = sp.parse_expr(y_src)
    z_expr = sp.parse_expr(z_src)

    def lam(expr: sp.Expr) -> Any:
        return sp.lambdify((u, v), expr, modules=["numpy"])

    eval_njit, deriv_njit, eval_cfn, deriv_cfn = _build_njit_functions(
        x_expr, y_expr, z_expr, x_src, y_src, z_src
    )

    return SurfaceFunctions(
        x_expr=x_expr,
        y_expr=y_expr,
        z_expr=z_expr,
        eval_x=lam(x_expr),
        eval_y=lam(y_expr),
        eval_z=lam(z_expr),
        d_x_du=lam(sp.diff(x_expr, u)),
        d_y_du=lam(sp.diff(y_expr, u)),
        d_z_du=lam(sp.diff(z_expr, u)),
        d_x_dv=lam(sp.diff(x_expr, v)),
        d_y_dv=lam(sp.diff(y_expr, v)),
        d_z_dv=lam(sp.diff(z_expr, v)),
        eval_njit=eval_njit,
        deriv_njit=deriv_njit,
        eval_cfn=eval_cfn,
        deriv_cfn=deriv_cfn,
    )
