_CODEGEN_TAG = "3"
_CODEGEN_DIR = os.path.join(tempfile.gettempdir(), "optics_codegen")

_GENERATED_MODULE = '''"""Generated by optics.surface expression codegen; do not edit."""
import math

import numpy as np
from numba import cfunc, carray, njit, types
from numba.extending import intrinsic

# The cfuncs take raw output addresses (uint64) so every caller in the
# solver kernels sees one stable C signature; the int-to-pointer cast is
# confined to these cfunc bodies (which cannot be disk-cached anyway),
# keeping the nopython solver chain free of dynamic globals.
_UINT64 = types.uint64


@intrinsic
def _int_to_f64ptr(typingctx, addr):
    ptr = types.CPointer(types.float64)
    sig = ptr(addr)

    def codegen(context, builder, signature, args):
        llt = context.get_value_type(signature.return_type)
        return builder.inttoptr(args[0], llt)

    return sig, codegen


_EVAL_SIG = types.void(types.float64, types.float64, _UINT64)
_DERIV_SIG = types.void(types.float64, types.float64, _UINT64, _UINT64)


@njit(cache=True)
def _sdiv(a, b):
    """Division with numpy scalar semantics (nan/inf instead of ZeroDivisionError)."""
    if b == 0.0:
        if a == 0.0:
            return math.nan
        return math.copysign(math.inf, a)
    return a / b


@njit(cache=True)
def _smod(a, b):
    """Modulo with numpy scalar semantics (nan instead of ZeroDivisionError)."""
    if b == 0.0:
        return math.nan
    return a % b


@njit(cache=True)
def eval_local(u, v):
    return np.array([{x}, {y}, {z}], dtype=np.float64)


@njit(cache=True)
def derivatives_local(u, v):
    return (
        np.array([{xu}, {yu}, {zu}], dtype=np.float64),
        np.array([{xv}, {yv}, {zv}], dtype=np.float64),
    )


@cfunc(_EVAL_SIG)
def eval_cfn(u, v, addr):
    out = carray(_int_to_f64ptr(addr), 3)
    p = eval_local(u, v)
    out[0] = p[0]
    out[1] = p[1]
    out[2] = p[2]


@cfunc(_DERIV_SIG)
def deriv_cfn(u, v, ru_addr, rv_addr):
    ru_out = carray(_int_to_f64ptr(ru_addr), 3)
    rv_out = carray(_int_to_f64ptr(rv_addr), 3)
    ru, rv = derivatives_local(u, v)
    ru_out[0] = ru[0]
    ru_out[1] = ru[1]
    ru_out[2] = ru[2]
    rv_out[0] = rv[0]
    rv_out[1] = rv[1]
    rv_out[2] = rv[2]
'''


class _SafeDivRewriter(ast.NodeTransformer):
    """Rewrite ``a / b`` and ``a % b`` into helpers with numpy scalar semantics.

    Numba's nopython mode raises ``ZeroDivisionError`` where NumPy would
    return ``inf``/``nan``; the generated surface code must keep the NumPy
    behavior the lambdified fallback has always had.
    """

    def _wrap(self, node: ast.BinOp, name: str) -> ast.Call:
        return ast.Call(
            func=ast.Name(id=name, ctx=ast.Load()),
            args=[node.left, node.right],
            keywords=[],
        )

    def visit_BinOp(self, node: ast.BinOp) -> Any:
        self.generic_visit(node)
        if isinstance(node.op, ast.Div):
            return self._wrap(node, "_sdiv")
        if isinstance(node.op, ast.Mod):
            return self._wrap(node, "_smod")
        return node


def _scalar_code(expr: sp.Expr) -> str:
    """SymPy expression -> numba-compatible scalar Python source."""
    code = sp.printing.pycode(expr)
    tree = ast.parse(code, mode="eval")
    tree = _SafeDivRewriter().visit(tree)
    ast.fix_missing_locations(tree)
    return ast.unparse(tree)


def _codegen_module_name(key: str) -> str:
    return f"optics_codegen_{key}"


def _codegen_key(x_src: str, y_src: str, z_src: str) -> str:
    payload = f"{_CODEGEN_TAG}|{numba.__version__}|{x_src}|{y_src}|{z_src}"
    return hashlib.sha1(payload.encode("utf-8")).hexdigest()[:16]


def _import_generated_module(key: str, source: str) -> Any:
    name = _codegen_module_name(key)
    module = sys.modules.get(name)
    if module is not None:
        return module
    os.makedirs(_CODEGEN_DIR, exist_ok=True)
    path = os.path.join(_CODEGEN_DIR, f"gen_{key}.py")
    if not os.path.exists(path):
        tmp = f"{path}.{os.getpid()}.tmp"
        with open(tmp, "w", encoding="utf-8") as fh:
            fh.write(source)
        os.replace(tmp, path)
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load generated surface module {path!r}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def _build_njit_functions(
    x_expr: sp.Expr,
    y_expr: sp.Expr,
    z_expr: sp.Expr,
    x_src: str,
    y_src: str,
    z_src: str,
) -> "tuple[Any, Any, Any, Any]":
    """Compile scalar ``eval_local``/``derivatives_local`` njit kernels.

    Returns ``(None, None, None, None)`` when the expressions cannot be
    turned into nopython code; callers then keep using the lambdified NumPy
    path. The ``cfunc`` pair exposes the same math through a C function
    pointer type, which is identical for every surface, so the solver
    kernels compile (and disk-cache) once instead of once per surface.
    """
    u = sp.symbols("u")
    v = sp.symbols("v")
    try:
        source = _GENERATED_MODULE.format(
            x=_scalar_code(x_expr),
            y=_scalar_code(y_expr),
            z=_scalar_code(z_expr),
            xu=_scalar_code(sp.diff(x_expr, u)),
            yu=_scalar_code(sp.diff(y_expr, u)),
            zu=_scalar_code(sp.diff(z_expr, u)),
            xv=_scalar_code(sp.diff(x_expr, v)),
            yv=_scalar_code(sp.diff(y_expr, v)),
            zv=_scalar_code(sp.diff(z_expr, v)),
        )
        key = _codegen_key(x_src, y_src, z_src)
        module = _import_generated_module(key, source)
        eval_fn = module.eval_local
        deriv_fn = module.derivatives_local
        eval_fn(0.7, 0.35)
        deriv_fn(0.7, 0.35)
        if not probe_njit_pair(module.eval_cfn, module.deriv_cfn):
            return None, None, None, None
        return eval_fn, deriv_fn, module.eval_cfn, module.deriv_cfn
    except Exception:
        return None, None, None, None


@functools.lru_cache(maxsize=64)
def _compile_parametric_surface(x_src: str, y_src: str, z_src: str) -> tuple[Any, ...]:
    u = sp.symbols("u")
    v = sp.symbols("v")
    x_expr = sp.parse_expr(x_src)
    y_expr = sp.parse_expr(y_src)
    z_expr = sp.parse_expr(z_src)

    def lam(expr: sp.Expr) -> Any:
        return sp.lambdify((u, v), expr, modules=["numpy"])

    eval_njit, deriv_njit, eval_cfn, deriv_cfn = _build_njit_functions(
        x_expr, y_expr, z_expr, x_src, y_src, z_src
    )

    return (
        x_expr,
        y_expr,
        z_expr,
        lam(x_expr),
        lam(y_expr),
        lam(z_expr),
        lam(sp.diff(x_expr, u)),
        lam(sp.diff(y_expr, u)),
        lam(sp.diff(z_expr, u)),
        lam(sp.diff(x_expr, v)),
        lam(sp.diff(y_expr, v)),
        lam(sp.diff(z_expr, v)),
        eval_njit,
        deriv_njit,
        eval_cfn,
        deriv_cfn,
    )

class Surface:
    def __init__(
        self,
        x_expr: Any,
        y_expr: Any,
        z_expr: Any,
        transform: "Transform | np.ndarray | None" = None,
        u_range: "Sequence[float]" = (-2.0, 2.0),
        v_range: "Sequence[float]" = (-2.0, 2.0),
        aperture: "Aperture | dict[str, Any] | None" = None,
    ) -> None:
        (
            self.x_expr,
            self.y_expr,
            self.z_expr,
            self._x,
            self._y,
            self._z,
            self._rx,
            self._ry,
            self._rz,
            self._sx,
            self._sy,
            self._sz,
            self._eval_njit,
            self._deriv_njit,
            self._eval_cfn,
            self._deriv_cfn,
        ) = _compile_parametric_surface(str(x_expr), str(y_expr), str(z_expr))
        if transform is None:
            self.transform = Transform(np.eye(3, 3), np.zeros(3))
        elif isinstance(transform, Transform):
            self.transform = transform
        else:
            self.transform = Transform(np.asarray(transform, dtype=float), np.zeros(3))
        self.u_range = (float(u_range[0]), float(u_range[1]))
        self.v_range = (float(v_range[0]), float(v_range[1]))
        self.aperture = Aperture.from_spec(aperture)
        self.solver = SurfaceSolver(self)
        self._graph_xy: bool | None = None
        self._njit_desc: tuple[Any, ...] | None = None
        self._njit_desc_built = False

    @property
    def njit_descriptor(self) -> "tuple[Any, ...] | None":
        """Flat tuple describing this surface for the nopython kernels.

        ``None`` when the surface cannot run in nopython mode (expression not
        compilable, or an aperture type the kernels do not understand), in
        which case callers fall back to the Python solver path.
        """
        if not self._njit_desc_built:
            self._njit_desc_built = True
            self._njit_desc = self._build_njit_descriptor()
        return self._njit_desc

    def _build_njit_descriptor(self) -> "tuple[Any, ...] | None":
        if self._eval_cfn is None or self._deriv_cfn is None:
            return None
        if self.aperture is None:
            ap_r, ap_cx, ap_cy = -1.0, 0.0, 0.0
        elif isinstance(self.aperture, CircularAperture):
            ap_r = self.aperture.radius
            ap_cx = float(self.aperture.center[0])
            ap_cy = float(self.aperture.center[1])
        else:
            return None
        (u_min, u_max), (v_min, v_max) = self.parameter_range
        tu = _c.DOMAIN_TOL * max(1.0, u_max - u_min)
        tv = _c.DOMAIN_TOL * max(1.0, v_max - v_min)
        return build_descriptor(
            self._eval_cfn,
            self._deriv_cfn,
            u_min,
            u_max,
            v_min,
            v_max,
            tu,
            tv,
            ap_r,
            ap_cx,
            ap_cy,
            self.transform.rotation,
            self.transform.translation,
        )

    @property
    def is_graph_over_xy(self) -> bool:
        """Whether the surface is exactly ``(u, v, z(u, v))`` in local space.

        Sampled once and cached; lets callers read the height above a local
        ``(x, y)`` without running the parameter-inversion solver.
        """
        if self._graph_xy is None:
            self._graph_xy = self._check_graph_over_xy()
        return self._graph_xy

    def _check_graph_over_xy(self) -> bool:
        (u_min, u_max), (v_min, v_max) = self.parameter_range
        for u in np.linspace(u_min, u_max, 5)[1:-1]:
            for v in np.linspace(v_min, v_max, 5)[1:-1]:
                u = float(u)
                v = float(v)
                p = self.evaluate_local(u, v)
                if not np.all(np.isfinite(p)):
                    return False
                if (
                    abs(float(p[0]) - u) > _c.GRAPH_XY_TOL * max(1.0, abs(u))
                    or abs(float(p[1]) - v) > _c.GRAPH_XY_TOL * max(1.0, abs(v))
                ):
                    return False
        return True

    @property
    def parameter_range(self) -> "tuple[tuple[float, float], tuple[float, float]]":
        return (self.u_range, self.v_range)

    def point(self, u: float, v: float) -> np.ndarray:
        return self.transform.point_to_world(self.evaluate_local(u, v))

    def tangents(self, u: float, v: float) -> "tuple[np.ndarray, np.ndarray]":
        ru, rv = self.derivatives_local(u, v)
        return self.transform.vector_to_world(ru), self.transform.vector_to_world(rv)

    def _inside_aperture(self, u: float, v: float) -> bool:
        if self.aperture is None:
            return True

        return self.aperture.contains(self, u, v)

    def parameters_at(self, pos: np.ndarray | Sequence[float]) -> "tuple[float, float] | None":
        return self.solver.parameters_at(pos)

    def parameters_at_xy(
        self,
        x: float,
        y: float,
        seed: "tuple[float, float] | None" = None,
    ) -> "tuple[float, float] | None":
        return self.solver.parameters_at_xy(x, y, seed=seed)

    def normal_at(self, pos: np.ndarray | Sequence[float]) -> np.ndarray | None:
        uv = self.parameters_at(pos)
        if uv is None:
            return None
        return self.normal(uv[0], uv[1])

    def aperture_mask(
        self,
        U: np.ndarray,
        V: np.ndarray,
        X: np.ndarray,
        Y: np.ndarray,
        Z: np.ndarray,
    ) -> np.ndarray:
        finite = (
            np.isfinite(X)
            & np.isfinite(Y)
            & np.isfinite(Z)
        )

        if self.aperture is None:
            return finite

        return self.aperture.mask(self, U, V, X, Y, Z)

    def intersect(self, ray: Ray) -> Hit | None:
        return self.solver.intersect(ray)

    def evaluate(self, u: float, v: float) -> np.ndarray:
        """World-space point."""
        return self.transform.point_to_world(self.evaluate_local(u, v))

    def evaluate_local(self, U: Any, V: Any) -> np.ndarray:
        """Local-space point (can be array)."""
        U = np.asarray(U, dtype=float)
        V = np.asarray(V, dtype=float)
        if U.ndim == 0 and V.ndim == 0 and self._eval_njit is not None:
            return self._eval_njit(float(U), float(V))
        with np.errstate(invalid="ignore", divide="ignore"):
            if U.ndim == 0 and V.ndim == 0:
                u = float(U)
                v = float(V)
                return np.array(
                    [self._x(u, v), self._y(u, v), self._z(u, v)],
                    dtype=float,
                )
            U, V = np.broadcast_arrays(U, V)
            shape = U.shape
            X = np.asarray(self._x(U, V), dtype=float)
            Y = np.asarray(self._y(U, V), dtype=float)
            Z = np.asarray(self._z(U, V), dtype=float)

        X = np.broadcast_to(X, shape)
        Y = np.broadcast_to(Y, shape)
        Z = np.broadcast_to(Z, shape)

        return np.stack((X, Y, Z), axis=-1)

    def _analytic_derivatives(self, u: float, v: float) -> "tuple[np.ndarray, np.ndarray]":
        if self._deriv_njit is not None:
            return self._deriv_njit(float(u), float(v))
        with np.errstate(invalid="ignore", divide="ignore"):
            ru = np.array(
                [
                    float(self._rx(u, v)),
                    float(self._ry(u, v)),
                    float(self._rz(u, v)),
                ],
                dtype=float,
            )
            rv = np.array(
                [
                    float(self._sx(u, v)),
                    float(self._sy(u, v)),
                    float(self._sz(u, v)),
                ],
                dtype=float,
            )
        return ru, rv

    def _partial_local(self, u: float, v: float, du: float, dv: float) -> np.ndarray:
        """One-sided finite-difference partial derivative in direction ``(du, dv)``.

        The step is halved until the evaluation stays finite, so it still works
        right at the edge of the domain or aperture.
        """
        base = self.evaluate_local(u, v)
        if not np.all(np.isfinite(base)):
            return np.full(3, np.nan)
        step = _c.FD_STEP_REL * max(1.0, abs(u), abs(v))
        for sign in (1.0, -1.0):
            h = step
            for _ in range(_c.FD_STEP_SHRINKS):
                p = self.evaluate_local(u + sign * du * h, v + sign * dv * h)
                if np.all(np.isfinite(p)):
                    return (p - base) / (sign * h)
                h *= 0.5
        return np.full(3, np.nan)

    def _interior_derivatives(self, u: float, v: float) -> "tuple[np.ndarray, np.ndarray]":
        """Tangents at the nearest interior point, used where they blow up.

        At an aperture rim a graph surface becomes vertical and its partial
        derivatives diverge. Pulling back toward the interior of the parameter
        domain and evaluating there gives the limiting tangent directions,
        which is the geometrically correct rim frame.
        """
        (u_min, u_max), (v_min, v_max) = self.parameter_range
        du = 0.5 * (u_min + u_max) - u
        dv = 0.5 * (v_min + v_max) - v
        if du == 0.0 and dv == 0.0:
            return self._partial_local(u, v, 1.0, 0.0), self._partial_local(u, v, 0.0, 1.0)
        span = max(abs(u_max - u_min), abs(v_max - v_min), 1.0)
        length = float(np.hypot(du, dv))
        frac = _c.DERIV_INTERIOR_FRAC * span / length
        for _ in range(_c.DERIV_INTERIOR_TRIES):
            if frac >= 1.0:
                break
            uu = u + du * frac
            vv = v + dv * frac
            if self.accepts_parameters(uu, vv):
                ru, rv = self._analytic_derivatives(uu, vv)
                if np.all(np.isfinite(ru)) and np.all(np.isfinite(rv)):
                    return ru, rv
            frac *= 2.0
        return self._partial_local(u, v, 1.0, 0.0), self._partial_local(u, v, 0.0, 1.0)

    def derivatives_local(self, u: float, v: float) -> "tuple[np.ndarray, np.ndarray]":
        """Return du and dv tangent vectors."""
        u = float(u)
        v = float(v)
        ru, rv = self._analytic_derivatives(u, v)
        if not (np.all(np.isfinite(ru)) and np.all(np.isfinite(rv))):
            ru, rv = self._interior_derivatives(u, v)
        return ru, rv

    def normal(self, u: float, v: float) -> np.ndarray | None:
        """World-space unit normal."""
        if not self.accepts_parameters(u, v):
            return None

        ru, rv = self.derivatives_local(u, v)
        n = -np.cross(ru, rv)
        norm = np.linalg.norm(n)
        if not np.isfinite(norm) or norm <= 0.0:
            return None
        return self.transform.vector_to_world(n / norm)

    def in_domain(self, u: Any, v: Any) -> Any:
        """Vectorized check whether parameters (u, v) lie in the domain."""
        tu = _c.DOMAIN_TOL * max(1.0, abs(self.u_range[1] - self.u_range[0]))
        tv = _c.DOMAIN_TOL * max(1.0, abs(self.v_range[1] - self.v_range[0]))

        return (
            (u >= self.u_range[0] - tu)
            & (u <= self.u_range[1] + tu)
            & (v >= self.v_range[0] - tv)
            & (v <= self.v_range[1] + tv)
        )

    def contains_parameters(self, u: float, v: float) -> bool:
        """Whether (u,v) is in the surface domain."""
        return bool(self.in_domain(float(u), float(v)))

    def accepts_parameters(self, u: float, v: float) -> bool:
        """Includes aperture restrictions."""
        if not self.contains_parameters(u, v):
            return False

        return self._inside_aperture(u, v)